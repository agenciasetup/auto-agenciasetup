// A versão pedida (ou a atual) de uma licença, já com a chave e os endereços das páginas. Nula se não existir.
export function licencaDe(chave, versao = null) {
  const l = LICENCAS[String(chave || '')];
  if (!l) return null;
  const v = String(versao || l.atual);
  const t = Object.prototype.hasOwnProperty.call(l.versoes, v) ? l.versoes[v] : null;
  if (!t) return null;
  return { chave, nome: l.nome, versao: v, atual: v === l.atual, ...t, licenca_url: `/cursos/${chave}/licenca`, termo_url: `/cursos/${chave}/termo` };
}

// A caixa de aceite de uma oferta: checkout.aceite = { licenca: '<chave>', versao, texto?, licenca_url?, termo_url? }.
// Nula quando a oferta não pede aceite. `invalida` quando pede uma licença ou versão que não existe aqui: aí a oferta
// não vende (lib/vendas.js recusa o pedido), para nunca vender sem o texto que a pessoa aceitou.
export function aceiteDaOferta(oferta) {
  const a = oferta && oferta.checkout && oferta.checkout.aceite;
  if (!a || typeof a !== 'object') return null;
  const l = licencaDe(a.licenca, a.versao);
  if (!l) return { invalida: true };
  const v = l.atual ? '' : `?v=${encodeURIComponent(l.versao)}`;
  return { versao: l.versao, texto: String(a.texto || l.caixa), licenca_url: a.licenca_url || `${l.licenca_url}${v}`, termo_url: a.termo_url || `${l.termo_url}${v}`, l };
}

// O hash (SHA-256) do que a pessoa aceitou: a frase da caixa, a licença e o termo da versão, nessa ordem, separados por
// uma linha em branco. Gravado no aceite: com o texto desta versão aqui, dá para provar depois que foi esse o texto.
export async function hashDoAceite(caixa, l) {
  const dados = new TextEncoder().encode([caixa, l.licenca, l.termo].join('\n\n'));
  const h = await crypto.subtle.digest('SHA-256', dados);
  return [...new Uint8Array(h)].map((b) => b.toString(16).padStart(2, '0')).join('');
}
